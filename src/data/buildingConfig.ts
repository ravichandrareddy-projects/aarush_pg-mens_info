// Helper function to generate bed list for a room
function generateBeds(roomId: string, roomNumber: string, floorId: string, floorName: string, capacity: number): Bed[] {
  const beds: Bed[] = [];
  for (let i = 1; i <= capacity; i++) {
    beds.push({
      id: `${roomNumber}-B${i}`,
      bedNumber: i,
      roomId,
      roomNumber,
      floorId,
      floorName,
      status: 'EMPTY'
    });
  }
  return beds;
}

